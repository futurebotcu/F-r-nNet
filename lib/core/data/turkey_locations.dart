  static final UnmodifiableMapView<String, TurkeyProvince> _byCode =
      UnmodifiableMapView<String, TurkeyProvince>(<String, TurkeyProvince>{
        for (final p in provinces) p.code: p,
      });

  static TurkeyProvince? findProvinceByCode(String? code) {
    if (code == null || code.isEmpty) return null;
    return _byCode[code];
  }

  static TurkeyDistrict? findDistrict(
    String? provinceCode,
    String? districtCode,
  ) {
    if (provinceCode == null || districtCode == null) return null;
    final p = findProvinceByCode(provinceCode);
    if (p == null) return null;
    for (final d in p.districts) {
      if (d.code == districtCode) return d;
    }
    return null;
  }

  /// İl adından lookup (controlled vocabulary'ye uyum için).
  static TurkeyProvince? findProvinceByName(String? name) {
    if (name == null || name.isEmpty) return null;
    for (final p in provinces) {
      if (p.name == name) return p;
    }
    return null;
  }
